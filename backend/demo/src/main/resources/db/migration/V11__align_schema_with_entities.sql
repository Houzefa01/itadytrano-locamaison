-- Aligne le schéma Flyway sur les entités JPA (écarts auparavant masqués par
-- hibernate.ddl-auto=update, désormais en mode 'validate').

-- 1) reservations.date_visite : l'entité Reservation.dateVisite est un LocalDate (DATE),
--    mais V1 l'avait créé en timestamp.
ALTER TABLE public.reservations
    ALTER COLUMN date_visite TYPE date USING date_visite::date;

-- 2) Table verification_codes (entité VerificationCode) : jamais créée par une migration,
--    elle était générée à la volée par Hibernate.
CREATE TABLE IF NOT EXISTS public.verification_codes (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone_number varchar(255) NOT NULL,
    code         varchar(6)   NOT NULL,
    expiry_date  timestamp(6) NOT NULL,
    used         boolean      NOT NULL DEFAULT false
);
