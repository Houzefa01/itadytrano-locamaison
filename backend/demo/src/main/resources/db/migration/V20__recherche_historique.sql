-- Historique des recherches des utilisateurs
CREATE TABLE public.recherche_historique (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id bigint NOT NULL REFERENCES public.utilisateurs (id) ON DELETE CASCADE,
    criteres       varchar(500),
    created_at     timestamp(6)
);
CREATE INDEX idx_recherche_hist_user ON public.recherche_historique (utilisateur_id);
