-- Suivi des vues UNIQUES par personne.
-- Une même personne (utilisateur connecté « u:<id> » ou visiteur anonyme
-- identifié par son IP « ip:<adresse> ») ne compte qu'une seule fois par annonce :
-- le compteur logements.vues n'est incrémenté qu'à l'insertion d'une nouvelle ligne.
CREATE TABLE public.logement_vues (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    logement_id bigint       NOT NULL REFERENCES public.logements (id) ON DELETE CASCADE,
    viewer      varchar(120) NOT NULL,
    created_at  timestamp(6) NOT NULL DEFAULT now(),
    CONSTRAINT uk_logement_vue UNIQUE (logement_id, viewer)
);
CREATE INDEX idx_logement_vues_logement ON public.logement_vues (logement_id);
