-- Signalements (annonces / comptes / avis abusifs)
CREATE TABLE public.signalements (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    signaleur_id bigint NOT NULL REFERENCES public.utilisateurs (id) ON DELETE CASCADE,
    cible        varchar(20) NOT NULL,
    cible_id     bigint NOT NULL,
    motif        varchar(500) NOT NULL,
    statut       varchar(20) NOT NULL,
    created_at   timestamp(6)
);
CREATE INDEX idx_signalement_statut ON public.signalements (statut);
