-- Historique de disponibilité / statut des logements
CREATE TABLE public.disponibilite_historique (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    logement_id    bigint NOT NULL REFERENCES public.logements (id) ON DELETE CASCADE,
    statut         varchar(20),
    disponible     boolean,
    date_changement timestamp(6)
);
CREATE INDEX idx_dispo_hist_logement ON public.disponibilite_historique (logement_id);
