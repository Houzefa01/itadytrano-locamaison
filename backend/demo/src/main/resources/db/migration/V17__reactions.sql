-- Réactions (j'aime / j'aime pas) sur les logements
CREATE TABLE public.reactions (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id bigint NOT NULL REFERENCES public.utilisateurs (id) ON DELETE CASCADE,
    logement_id    bigint NOT NULL REFERENCES public.logements (id) ON DELETE CASCADE,
    type           varchar(10) NOT NULL,
    created_at     timestamp(6),
    CONSTRAINT uq_reaction_user_logement UNIQUE (utilisateur_id, logement_id)
);
