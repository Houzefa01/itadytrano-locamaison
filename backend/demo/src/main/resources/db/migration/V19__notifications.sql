-- Notifications persistées (centre de notifications + historique)
CREATE TABLE public.notifications (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    destinataire_id bigint NOT NULL REFERENCES public.utilisateurs (id) ON DELETE CASCADE,
    type            varchar(50)  NOT NULL,
    message         varchar(500) NOT NULL,
    lien            varchar(255),
    lu              boolean NOT NULL DEFAULT false,
    created_at      timestamp(6)
);
CREATE INDEX idx_notif_destinataire ON public.notifications (destinataire_id);
