-- Calendrier de disponibilité (créneaux datés)
CREATE TABLE public.creneaux (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    logement_id bigint NOT NULL REFERENCES public.logements (id) ON DELETE CASCADE,
    date_creneau date NOT NULL,
    heure_debut varchar(5),
    heure_fin   varchar(5),
    disponible  boolean NOT NULL DEFAULT true
);
CREATE INDEX idx_creneau_logement ON public.creneaux (logement_id);
